function messageAt(locale, key) {
  return key.split('.').reduce((value, part) => value?.[part], MESSAGES[locale])
}

export function normalizeLocale(value) {
  const locale = String(value || '').toLowerCase()
  if (locale.startsWith('en')) return 'en'
  return 'ru'
}

export function localeTag(locale) {
  return normalizeLocale(locale) === 'en' ? 'en-US' : 'ru-RU'
}

export function translate(locale, key, params = {}) {
  const normalized = normalizeLocale(locale)
  const template = messageAt(normalized, key) ?? messageAt('ru', key) ?? key
  return String(template).replace(/\{(\w+)\}/g, (_, name) => (
    Object.prototype.hasOwnProperty.call(params, name) ? String(params[name]) : `{${name}}`
  ))
}

export function formatLocaleDate(value, locale, options) {
  if (!value) return '—'
  const date = new Date(value)
  if (Number.isNaN(date.getTime())) return '—'
  return date.toLocaleDateString(localeTag(locale), options || {
    day: '2-digit',
    month: '2-digit',
    year: 'numeric',
  })
}

export function formatLocaleTime(value, locale) {
  const date = value ? new Date(value) : new Date()
  if (Number.isNaN(date.getTime())) return '—'
  return date.toLocaleTimeString(localeTag(locale), { hour: '2-digit', minute: '2-digit' })
}
